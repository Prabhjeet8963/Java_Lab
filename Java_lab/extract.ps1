Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [System.IO.Compression.ZipFile]::OpenRead("c:\Users\LENOVO\Desktop\coding\Java_lab\OOps.docx")
$entry = $zip.GetEntry("word/document.xml")
$stream = $entry.Open()
