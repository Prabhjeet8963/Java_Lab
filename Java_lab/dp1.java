// Inheritance is a fundamental concept that allows a new class (child class)
// to inherit properties and behaviors (methods) from an existing class
// (parent class). This promotes code reusability and establishes a natural 
// hierarchical relationship between classes.
//
// Types of inheritance 
// 1. Single Inheritance: A child class inherits from a single parent class.
// 2. Multilevel Inheritance: A child class inherits from a parent class, which in turn inherits from another parent class.
// 3. Hierarchical Inheritance: Multiple child classes inherit from a single parent class.

public class dp1 {
    void show() {
        System.out.println("This is the Parent class dp1");
    }
}